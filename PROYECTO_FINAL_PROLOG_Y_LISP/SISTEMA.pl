    (   template(Stim, Resp, Vars), match(Stim, Input) ->
        nth0(0, Resp, Flag), 
        tratar_respuesta(Flag, Vars, Input),
        !
    ;   writeln('EVZU: Escribe bien tu pregunta.'),
        true
    ).

