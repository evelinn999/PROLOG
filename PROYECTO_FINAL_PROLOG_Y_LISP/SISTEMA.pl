% Regla para identificar quién es padre (hombre que tiene un hijo)
padre(P, H) :- padrede(P, H), hombres(P).

% Regla para identificar quién es madre (mujer que tiene un hijo)
madre(M, H) :- madrede(M, H), mujeres(M).

% Regla de hermano (usa tus predicados hermanode y hombres)
% X es hermano de Y si está en tu lista de hermanode y es hombre
hermano(X, Y) :- 
    (hermanode(X, Y); hermanade(X, Y)), 
    hombres(X).

% Regla de hermana (usa tus predicados hermanade y mujeres)
hermana(X, Y) :- 
    (hermanode(X, Y); hermanade(X, Y)), 
    mujeres(X).

% Regla de tío (basada en tus hechos tiode)
tio(T, S) :- tiode(T, S).

% Regla de tía (basada en tus hechos tiade)
tia(T, S) :- tiade(T, S).

% Regla de abuelo (X es abuelo de Y si es padre de alguien que es padre/madre de Y)
% Nota: como tú no tienes 'abuelode' para hombres, la construimos así:
abuelo(A, N) :- 
    padrede(A, P), 
    (padrede(P, N); madrede(P, N)), 
    hombres(A).

% Regla de abuela (basada en tu predicado abuelade)
abuela(A, N) :- abuelade(A, N).

% Regla de nieto (X es nieto de Y si Y es su abuelo/abuela y X es hombre)
nieto(N, A) :- 
    (abuelo(A, N); abuela(A, N)), 
    hombres(N).

% Regla de nieta (X es nieta de Y si Y es su abuelo/abuela y X es mujer)
nieta(N, A) :- 
    (abuelo(A, N); abuela(A, N)), 
    mujeres(N).

% Regla de sobrino (X es sobrino de Y si X es hombre y Y es su tío/tía)
% Usamos tus predicados sobrinode
sobrino(X, Y) :- sobrinode(X, Y).

% Regla de sobrina (X es sobrina de Y si X es mujer y Y es su tío/tía)
% Usamos tus predicados sobrinade
sobrina(X, Y) :- sobrinade(X, Y).

