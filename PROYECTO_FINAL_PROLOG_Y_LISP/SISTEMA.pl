% --- MOTOR INTERACTIVO AUXILIAR ---

realizar_interrogatorio([], Puntos, Puntos).
realizar_interrogatorio([S|Resto], PuntosActuales, TotalPuntos) :-
    format('EVZU: ¿Sientes ~w? (si/no) ', [S]),
    read_line_to_string(user_input, Resp),
    ( (Resp == "si" ; Resp == "Si" ; Resp == "SI") -> NuevosPuntos is PuntosActuales + 1 ; NuevosPuntos is PuntosActuales ),
    realizar_interrogatorio(Resto, NuevosPuntos, TotalPuntos).

evaluar_diagnostico(Enf, Puntos, Total) :-
    (Puntos =:= 1 -> 
        writeln('EVZU: Solo tienes un sintoma. Te sugiero paracetamol y reposo :) ')
    ;   
        Porcentaje is (Puntos / Total) * 100,
        informe_medico_detallado(Enf, Porcentaje, Puntos, Total)
    ).

informe_medico_detallado(Enf, Porc, P, T) :-
    nl, writeln(''),
    writeln('DIAGNOSTICO COMPLETO GENERADO POR EVZU'),
    writeln(''),
    format('ENFERMEDAD: ~w (~w% de coincidencia)~n', [Enf, Porc]),
    format('SINTOMAS POSITIVOS: ~w de ~w~n', [P, T]),
    nl, writeln('PLAN MEDICO'),
    (especialista(Enf, Esp) -> format('ESPECIALISTA: ~w~n', [Esp]); true),
    (medicamento(Enf, Med) -> format('MEDICAMENTO: ~w~n', [Med]); true),
    (lugar_atencion(Enf, Lug) -> 
        format('LUGAR: ~w~n', [Lug]),
        (ubicacion_lugar_atencion(Lug, Ubic) -> format('DIRECCION: ~w~n', [Ubic]); true)
    ; true),
    nl, writeln('DATOS EXTRA'),
    (factor_riesgo(Enf, Ries) -> format('FACTOR RIESGO: ~w~n', [Ries]); true),
    (antecedente_familiar(Enf, Ant) -> format('ANTECEDENTES: ~w~n', [Ant]); true),
    (alimento_recomendado(Enf, Ali) -> format('DIETA: ~w~n', [Ali]); true),
    writeln(''), nl.

